"""
Builds the AHS monogram from Cormorant Garamond outlines (SIL Open Font
Licence) and writes:
  src/data/monogram.ts   path data used by the React monogram component
  src/app/icon.svg       favicon
  public/brand/monogram.svg

Usage: python scripts/monogram.py path/to/CormorantGaramond.woff2
"""
import math, os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1]
font = TTFont(src)
if "fvar" in font:
    from fontTools.varLib.instancer import instantiateVariableFont
    font = instantiateVariableFont(font, {"wght": 500})
gs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm


def glyph_path(ch, scale, dx, dy):
    """SVG path for a character, scaled, flipped to SVG y-down, moved by dx, dy (baseline)."""
    name = cmap[ord(ch)]
    pen = SVGPathPen(gs)
    tp = TransformPen(pen, (scale, 0, 0, -scale, dx, dy))
    gs[name].draw(tp)
    return pen.getCommands()


def glyph_bounds(ch):
    bp = BoundsPen(gs)
    gs[cmap[ord(ch)]].draw(bp)
    return bp.bounds, gs[cmap[ord(ch)]].width


# Canvas 100 x 120: a cusped Jaipur arch, letters set on a baseline inside it.
W, H = 100, 120
cap = 27.0  # cap height in canvas units
(ax0, ay0, ax1, ay1), aw = glyph_bounds("A")
(hx0, hy0, hx1, hy1), hw = glyph_bounds("H")
(sx0, sy0, sx1, sy1), sw = glyph_bounds("S")
s = cap / (hy1 - hy0)
# Interlock: A and S tuck into the H's stems.
overlap = 0.16 * (hx1 - hx0) * s
widths = [(ax1 - ax0) * s, (hx1 - hx0) * s, (sx1 - sx0) * s]
total = sum(widths) - 2 * overlap
x = (W - total) / 2
base = 88.0
paths = []
for ch, (x0, _, x1, _), wdt in zip("AHS", [(ax0, ay0, ax1, ay1), (hx0, hy0, hx1, hy1), (sx0, sy0, sx1, sy1)], widths):
    paths.append(glyph_path(ch, s, x - x0 * s, base))
    x += wdt - overlap
letters = " ".join(paths)


def arch(inset):
    """A multifoil pointed arch on straight jambs: the window of a Jaipur jharokha."""
    l, r = 8 + inset, W - 8 - inset
    bottom = H - 6 - inset
    cx = W / 2
    half = cx - l
    d = half * 0.28  # offset of each arc's centre: a gentle point at the crown
    R = half + d
    spring = 6 + inset + math.sqrt(R * R - d * d)  # so the crown sits just inside the view box
    # Left arc: centre (cx + d, spring), from angle pi (the jamb) to the apex.
    apex_ang = math.acos(d / R)  # angle (from +x) where the arc reaches x = cx
    a0, a1 = math.pi, math.pi - apex_ang
    lobes = 3
    pts = [(cx + d + R * math.cos(a0 + (a1 - a0) * k / lobes), spring - R * math.sin(a0 + (a1 - a0) * k / lobes)) for k in range(lobes + 1)]
    path = f"M{l:.2f},{bottom:.2f} L{l:.2f},{spring:.2f}"
    def lobe(p0, p1, centre):
        mx, my = (p0[0] + p1[0]) / 2, (p0[1] + p1[1]) / 2
        vx, vy = mx - centre[0], my - centre[1]
        ln = math.hypot(vx, vy) or 1
        depth = 5.2 - inset * 0.5
        return f" Q{mx + vx / ln * depth:.2f},{my + vy / ln * depth:.2f} {p1[0]:.2f},{p1[1]:.2f}"
    for k in range(lobes):
        path += lobe(pts[k], pts[k + 1], (cx + d, spring))
    rpts = [(W - x, y) for (x, y) in reversed(pts)]
    for k in range(lobes):
        path += lobe(rpts[k], rpts[k + 1], (cx - d, spring))
    path += f" L{r:.2f},{bottom:.2f} Z"
    return path


outer = arch(0)
inner = arch(3.2)
# A fine rule under the letters, and a small kundan petal at the arch's crown.
rule = f"M{W/2-14:.1f},{base+7:.1f} L{W/2+14:.1f},{base+7:.1f}"
petal = f"M{W/2:.1f},{base+11:.1f} q2.6,2.6 0,5.2 q-2.6,-2.6 0,-5.2 Z"

ts = f"""/**
 * The AHS monogram, generated by scripts/monogram.py from Cormorant Garamond
 * (SIL Open Font Licence). Interlocked serif letters inside a cusped Jaipur
 * arch. View box 0 0 {W} {H}.
 */
export const MONOGRAM = {{
  viewBox: "0 0 {W} {H}",
  outer: "{outer}",
  inner: "{inner}",
  letters: "{letters}",
  rule: "{rule}",
  petal: "{petal}",
}} as const;
"""
open(os.path.join(ROOT, "src", "data", "monogram.ts"), "w", encoding="utf-8").write(ts)


def svg(stroke, fill, bg=None, pad=0):
    vb = f"{-pad} {-pad} {W + 2 * pad} {H + 2 * pad}"
    back = f'<rect x="{-pad}" y="{-pad}" width="{W + 2 * pad}" height="{H + 2 * pad}" fill="{bg}"/>' if bg else ""
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}">{back}
<path d="{outer}" fill="none" stroke="{stroke}" stroke-width="1.6" stroke-linejoin="round"/>
<path d="{inner}" fill="none" stroke="{stroke}" stroke-width="0.7" stroke-linejoin="round"/>
<path d="{letters}" fill="{fill}"/>
<path d="{rule}" stroke="{stroke}" stroke-width="0.7"/>
<path d="{petal}" fill="{stroke}"/>
</svg>'''


os.makedirs(os.path.join(ROOT, "public", "brand"), exist_ok=True)
open(os.path.join(ROOT, "public", "brand", "monogram.svg"), "w", encoding="utf-8").write(svg("#B08D57", "#1A1714"))
open(os.path.join(ROOT, "public", "brand", "monogram-light.svg"), "w", encoding="utf-8").write(svg("#E8DBC4", "#FAF7F2", "#1A1714", 14))
# Favicon: ink tile, gold mark, square.
fav = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="-20 -10 140 140"><rect x="-20" y="-10" width="140" height="140" rx="0" fill="#1A1714"/>
<path d="{outer}" fill="none" stroke="#C9A86A" stroke-width="2.6" stroke-linejoin="round"/>
<path d="{letters}" fill="#F3E7CF"/>
</svg>'''
open(os.path.join(ROOT, "src", "app", "icon.svg"), "w", encoding="utf-8").write(fav)
